// Builds assets/index.js and writes sw.js, the service worker, with the list of files it caches and the build version.
// `node scripts/build.mjs --watch` rebuilds on source changes.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import * as esbuild from "esbuild";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = "assets/index.js";
// the bundle carries its build version; it's hashed with this placeholder in place, then the placeholder is swapped
const PLACEHOLDER = "__aegirv__";
// pictures load as they're needed; everything else is needed to start the app offline
const LAZY = /\.(png|jpe?g|webp|gif)$/;
const PRECACHED_IMAGES = new Set(["assets/gfx/placeholder.png"]);

function listFiles(dir) {
	const out = [];
	for (const entry of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
		const rel = `${dir}/${entry.name}`;
		// gfx/src lists where the pictures come from
		if (entry.name === "src") continue;
		if (entry.isDirectory()) {
			out.push(...listFiles(rel));
		} else if (!entry.name.endsWith(".map")) {
			out.push(rel);
		}
	}
	return out;
}

function writeIfChanged(rel, contents) {
	const file = path.join(ROOT, rel);
	const current = fs.existsSync(file) ? fs.readFileSync(file) : null;
	if (current && Buffer.compare(current, Buffer.from(contents)) === 0) return;
	fs.writeFileSync(file, contents);
}

function finish(outputFiles) {
	const bundle = outputFiles.find(f => f.path.endsWith(".js"));
	const map = outputFiles.find(f => f.path.endsWith(".js.map"));
	const worker = fs.readFileSync(path.join(ROOT, "src/sw.js"), "utf8");

	const files = ["index.html", ...listFiles("assets")].sort();
	const hash = crypto.createHash("sha256").update(worker);
	for (const rel of files) {
		const contents = rel === OUT ? bundle.contents : fs.readFileSync(path.join(ROOT, rel));
		hash.update(`${rel}\n`).update(contents);
	}
	const version = hash.digest("hex").slice(0, PLACEHOLDER.length);
	const precache = ["./", ...files.filter(f => f !== "index.html" && (!LAZY.test(f) || PRECACHED_IMAGES.has(f)))];

	writeIfChanged(OUT, bundle.text.replaceAll(PLACEHOLDER, version));
	writeIfChanged(`${OUT}.map`, map.contents);
	writeIfChanged("sw.js", `// generated by scripts/build.mjs from src/sw.js\nconst MANIFEST = ${JSON.stringify({ version, precache })};\n${worker}`);
	console.log(`built ${version}`);
}

const options = {
	absWorkingDir: ROOT,
	entryPoints: ["src/index.ts"],
	bundle: true,
	sourcemap: true,
	loader: { ".html": "text" },
	outfile: OUT,
	write: false,
	define: { AEGIR_BUILD: JSON.stringify(PLACEHOLDER) },
	plugins: [{
		name: "service-worker",
		setup(build) {
			build.onEnd(result => {
				if (result.errors.length === 0) finish(result.outputFiles);
			});
		}
	}]
};

if (process.argv.includes("--watch")) {
	const context = await esbuild.context(options);
	await context.watch();
} else {
	await esbuild.build(options);
}
